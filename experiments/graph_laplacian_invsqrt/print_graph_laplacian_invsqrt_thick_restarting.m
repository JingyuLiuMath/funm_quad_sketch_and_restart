exp_graph_laplacian_invsqrt_settings;

% Use the same dimension limit and median runs as the thick-restart plots.
selection.data_path = data_path;
selection.file_prefix = "frac_laplacian_invsqrt";
selection.krylov_dim = 150;

for sfactor = sfactor_list
    selection.sfactor = sfactor;
    if selection.krylov_dim ~= adaptive_krylov_dim ...
            || ~ismember("last_orth", adaptive_update_list)
        continue
    end

    % Use the same deterministic Arn reference as the main table's left half.
    selection.thick = false;
    baseline = graph_read_median_run(selection, "fixed", "arnoldi", inf);
    selection.thick = true;
    rows = struct('method_name', {}, 'error', {}, 'time', {}, ...
        'n_iter', {}, 'n_matvec', {}, 'm_act', {});
    for truncation_length = [2, 1, 0]
        info = graph_read_median_run(selection, "adaptive", "last_orth", truncation_length);
        label = "adaArn-" + string(truncation_length) + " (with thick restarting)";
        rows(end + 1) = thick_restart_row(label, info); %#ok<SAGROW>
    end

    output_file = fullfile(figure_path, ...
        "graph_laplacian_invsqrt_thick_restarting_table_krylov_dim_" ...
        + string(selection.krylov_dim) + "_sfactor_" + string(sfactor) + ".tex");
    print_thick_restart_table(rows, selection, baseline.t_total, output_file);
end

function row = thick_restart_row(label, info)
% Use the same fields and definitions as the main results table.
row = struct('method_name', string(label), 'error', info.final_err, ...
    'time', info.t_total, 'n_iter', info.iter, ...
    'n_matvec', sum(info.num_oracle(:)), 'm_act', mean(info.dim(:)));
end

function print_thick_restart_table(rows, selection, baseline_time, output_file)
sentences = [ ...
    "Adaptive Arnoldi methods with thick restarting for the graph Laplacian " + ...
        "inverse square root example (\(m_{\max}=" + string(selection.krylov_dim) + ...
        "\), \(\eta=" + string(selection.sfactor) + "\))."; ...
    "Columns report the relative error, runtime in seconds, number of restart " + ...
        "cycles \(n_{\mathrm{iter}}\), number of matrix-vector products " + ...
        "\(n_{\mathrm{matvec}}\), and mean actual Krylov subspace dimension per " + ...
        "cycle \(m_{\mathrm{act}}\), including retained directions."; ...
    "Speedup is the percentage runtime reduction relative to Arn without " + ...
        "thick restarting (\(m=" + string(selection.krylov_dim) + "\)), " + ...
        "\((t_{\mathrm{Arn}}-t)/t_{\mathrm{Arn}}\times100\%\)." ...
];
caption = strjoin(sentences, " ");
table_label = "tab:graph-laplacian-invsqrt-thick-restarting-krylov-dim-" ...
    + string(selection.krylov_dim) + "-sfactor-" + string(selection.sfactor);
latex_lines = [ ...
    "% Requires \usepackage{graphicx,booktabs} in the preamble."; ...
    "\begin{table}[htbp]"; ...
    "\centering"; ...
    "\caption{" + caption + "}"; ...
    "\label{" + table_label + "}"; ...
    "\resizebox{\textwidth}{!}{%"; ...
    "\begin{tabular}{@{}lrrrrrr@{}}"; ...
    "\toprule"; ...
    "method & error & time & \(n_{\mathrm{iter}}\) & " ...
        + "\(n_{\mathrm{matvec}}\) & \(m_{\mathrm{act}}\) & speedup \\"; ...
    "\midrule" ...
];
data_lines = strings(numel(rows), 1);
for row_index = 1:numel(rows)
    row = rows(row_index);
    speedup = 100 * (baseline_time - row.time) / baseline_time;
    cells = [string(row.method_name), graph_latex_scientific(row.error), ...
        string(sprintf('%.1f', row.time)), ...
        string(row.n_iter), string(row.n_matvec), ...
        string(sprintf('%.1f', row.m_act)), ...
        "\(" + string(sprintf('%.1f', speedup)) + "\%\)"];
    data_lines(row_index) = strjoin(cells, " & ") + " \\";
end
latex_lines = [latex_lines; data_lines; "\bottomrule"; "\end{tabular}%"; ...
    "}"; "\end{table}"];
latex_text = strjoin(latex_lines, newline) + newline;
fprintf('%s', latex_text);

fid = fopen(output_file, 'w');
assert(fid ~= -1, 'Cannot open LaTeX table output file: %s', output_file);
file_cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid, '%s', latex_text);
end

function text = graph_latex_scientific(value)
% Keep the main table's compact scientific notation, with no padded exponent.
if ~isfinite(value)
    text = "\(\mathrm{" + string(value) + "}\)";
    return
end
parts = split(string(sprintf('%.1e', value)), 'e');
text = parts(1) + "e" + string(str2double(parts(2)));
end

% Graph-local result loading and table formatting.

function info = graph_read_median_run(selection, mode, method, truncation_length)
%READ_MEDIAN_RUN Load the run with median total runtime for a configuration.
% selection supplies data_path, file_prefix, krylov_dim, sfactor, and thick.
% All reported values come from the same selected repeat.

mode = string(mode);
method = string(method);
factor = selection.sfactor;
if mode == "fixed" && ismember(method, ["arnoldi", "hmarnoldi"])
    factor = 0;
end
file_name = string(selection.file_prefix) + "_" + mode + "_" + method ...
    + "_krylov_dim_" + string(selection.krylov_dim) ...
    + "_sfactor_" + string(factor) ...
    + "_thick_" + string(double(selection.thick));
if mode == "adaptive"
    file_name = file_name + "_trunc_" + string(truncation_length);
end
data = load(fullfile(selection.data_path, file_name + ".mat"), "result");
repeat_index = find(data.result.t_list == median(data.result.t_list), 1);
info = data.result.info(repeat_index);
end
